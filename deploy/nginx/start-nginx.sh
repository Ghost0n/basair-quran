#!/bin/sh

set -eu

export QBASAIR_SERVER_NAME="${QBASAIR_PUBLIC_DOMAIN:-_}"
CONFIG_TEMPLATE="/opt/qbasair/http.conf.template"

if [ "${QBASAIR_ENABLE_TLS:-0}" = "1" ] && [ -n "${QBASAIR_PUBLIC_DOMAIN:-}" ]; then
    CERT_DIR="/etc/letsencrypt/live/${QBASAIR_PUBLIC_DOMAIN}"
    if [ -f "${CERT_DIR}/fullchain.pem" ] && [ -f "${CERT_DIR}/privkey.pem" ]; then
        CONFIG_TEMPLATE="/opt/qbasair/tls.conf.template"
        echo "Q-Basair nginx: TLS certificate found, starting HTTPS config."
    else
        echo "Q-Basair nginx: TLS requested but certificate not found yet, starting temporary HTTP config."
    fi
else
    echo "Q-Basair nginx: starting HTTP config."
fi

envsubst '${QBASAIR_SERVER_NAME} ${QBASAIR_PUBLIC_DOMAIN}' < "${CONFIG_TEMPLATE}" > /etc/nginx/conf.d/default.conf

# Behind a CDN (docs/caching.md → "Putting a CDN in front"): every request
# reaches nginx from the CDN's addresses, so the per-IP rate limits and logs
# would treat all readers as one. When the CDN's address ranges are given, the
# visitor's own IP is taken from the CDN's header — only from those addresses,
# never from anyone else who sends the header.
REALIP_CONF="/etc/nginx/conf.d/00-realip.conf"
rm -f "${REALIP_CONF}"
if [ -n "${QBASAIR_CDN_TRUSTED_RANGES:-}" ]; then
    {
        echo "# Generated by start-nginx.sh from QBASAIR_CDN_TRUSTED_RANGES."
        for range in $(echo "${QBASAIR_CDN_TRUSTED_RANGES}" | tr ',' ' '); do
            echo "set_real_ip_from ${range};"
        done
        echo "real_ip_header ${QBASAIR_CDN_REAL_IP_HEADER:-X-Forwarded-For};"
        echo "real_ip_recursive on;"
    } > "${REALIP_CONF}"
    echo "Q-Basair nginx: trusting the CDN's ${QBASAIR_CDN_REAL_IP_HEADER:-X-Forwarded-For} header from $(echo "${QBASAIR_CDN_TRUSTED_RANGES}" | tr ',' '\n' | wc -l) range(s)."
fi

exec nginx -g 'daemon off;'
