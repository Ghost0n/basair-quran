"""Quran translations of meanings — read side of data/translations.db.

The database is generated by ``scripts/build_translations.py`` from trusted
sources (QuranEnc first, Tanzil for the gaps) and opened read-only. Texts are
returned verbatim with their source attribution. Translations are keyed by
surah:ayah in Ḥafṣ numbering.

Translations are a reading aid, never evidence: the strict research agent does
not read this database.
"""

from __future__ import annotations

import re
import sqlite3
import threading
from pathlib import Path

from src.app.core import config

MAX_AYAHS_PER_REQUEST = 400
MAX_KEYS_PER_REQUEST = 3
_REF = re.compile(r"^(\d{1,3}):(\d{1,3})(?:-(\d{1,3}))?$")

_local = threading.local()


class TranslationRequestError(ValueError):
    pass


def _connect() -> sqlite3.Connection | None:
    path = Path(config.get_translations_db_path())
    cached = getattr(_local, "entry", None)
    if cached is not None:
        connection, cached_path, mtime = cached
        # Reopen after a rebuild swapped the file in.
        if cached_path == path and path.exists() and path.stat().st_mtime == mtime:
            return connection
        connection.close()
        _local.entry = None
    if not path.exists():
        return None
    connection = sqlite3.connect(path.resolve().as_uri() + "?mode=ro", uri=True, check_same_thread=False)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA query_only=ON")
    _local.entry = (connection, path, path.stat().st_mtime)
    return connection


def reset_connection() -> None:
    cached = getattr(_local, "entry", None)
    if cached is not None:
        cached[0].close()
        _local.entry = None


def catalogue() -> list[dict]:
    connection = _connect()
    if connection is None:
        return []
    rows = connection.execute(
        "SELECT key, language, kind, name, translator, description, source, source_url, terms, version, direction, "
        "ayah_count FROM translations ORDER BY kind, language, source, name"
    ).fetchall()
    return [dict(row) for row in rows]


def parse_refs(raw: str) -> list[tuple[int, int]]:
    """`2:1-7,3:5` → [(2,1)…(2,7),(3,5)] (deduplicated, in order, capped)."""
    refs: list[tuple[int, int]] = []
    seen: set[tuple[int, int]] = set()
    for part in (raw or "").split(","):
        part = part.strip()
        if not part:
            continue
        match = _REF.match(part)
        if not match:
            raise TranslationRequestError(f"Invalid reference: {part[:20]}")
        surah, start = int(match.group(1)), int(match.group(2))
        end = int(match.group(3) or start)
        if not 1 <= surah <= 114 or start < 1 or end < start or end > 286:
            raise TranslationRequestError(f"Invalid reference: {part[:20]}")
        for ayah in range(start, end + 1):
            ref = (surah, ayah)
            if ref not in seen:
                seen.add(ref)
                refs.append(ref)
            if len(refs) > MAX_AYAHS_PER_REQUEST:
                raise TranslationRequestError(f"At most {MAX_AYAHS_PER_REQUEST} ayahs per request.")
    return refs


def ayah_texts(keys: list[str], refs: list[tuple[int, int]]) -> dict:
    """The requested translations for the requested ayahs, in request order."""
    keys = list(dict.fromkeys(key for key in keys if key))[:MAX_KEYS_PER_REQUEST]
    connection = _connect()
    if connection is None or not keys or not refs:
        return {"translations": [], "ayahs": []}
    placeholders = ", ".join("?" for _ in keys)
    meta_rows = connection.execute(
        f"SELECT key, language, kind, name, translator, source, source_url, direction FROM translations WHERE key IN ({placeholders})",
        keys,
    ).fetchall()
    meta = {row["key"]: dict(row) for row in meta_rows}
    known = [key for key in keys if key in meta]
    if not known:
        return {"translations": [], "ayahs": []}
    texts: dict[tuple[int, int], dict[str, dict]] = {}
    surahs = sorted({surah for surah, _ in refs})
    for surah in surahs:
        ayahs = [ayah for s, ayah in refs if s == surah]
        rows = connection.execute(
            f"SELECT key, surah, ayah, text, footnotes FROM translation_ayahs WHERE surah = ? AND ayah BETWEEN ? AND ? "
            f"AND key IN ({', '.join('?' for _ in known)})",
            (surah, min(ayahs), max(ayahs), *known),
        ).fetchall()
        wanted = set(ayahs)
        for row in rows:
            if row["ayah"] in wanted:
                texts.setdefault((row["surah"], row["ayah"]), {})[row["key"]] = {
                    "key": row["key"],
                    "text": row["text"],
                    "footnotes": row["footnotes"],
                }
    return {
        "translations": [meta[key] for key in known],
        "ayahs": [
            {"surah": surah, "ayah": ayah, "texts": [texts[(surah, ayah)][key] for key in known if key in texts.get((surah, ayah), {})]}
            for surah, ayah in refs
        ],
    }
