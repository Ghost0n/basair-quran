def _read_int_env(name: str, default: int) -> int:
    raw = os.environ.get(name)
    if raw is None:
        return default
    try:
        return int(raw.strip())
    except ValueError:
        return default


def get_rate_limit(bucket: str) -> tuple[float, int]:
    """Return ``(window_seconds, max_requests)`` for a rate-limit bucket.

    A non-positive ``max_requests`` disables limiting for that bucket. Limits are
    per-IP sliding windows (single-process uvicorn); tune via env in production.
    """
    window = float(max(1, _read_int_env("QBASAIR_RATE_LIMIT_WINDOW_SECONDS", 60)))
    if bucket == "auth":
        return window, _read_int_env("QBASAIR_RATE_LIMIT_AUTH_MAX", 20)
    if bucket == "research":
        return window, _read_int_env("QBASAIR_RATE_LIMIT_RESEARCH_MAX", 60)
    if bucket == "community":
        return window, _read_int_env("QBASAIR_RATE_LIMIT_COMMUNITY_MAX", 30)
    if bucket == "feedback":
        return window, _read_int_env("QBASAIR_RATE_LIMIT_FEEDBACK_MAX", 10)
    return window, 0


# --- Community moderation (docs/community-moderation-design.md) --------------


def get_moderation_worker_mode() -> str:
    """Where the moderation batches run: ``embedded`` (a thread of the API — the
    default, so a single process works), ``external`` (the ``worker`` container
    runs them; the API doesn't) or ``off``."""
    mode = os.environ.get("QBASAIR_MODERATION_WORKER", "embedded").strip().lower()
    return mode if mode in ("embedded", "external", "off") else "embedded"


def get_moderation_interval_seconds() -> int:
    """Seconds between two moderation batches (15 minutes by default)."""
    return max(10, _read_int_env("QBASAIR_MODERATION_INTERVAL_SECONDS", 900))


def get_moderation_daily_budget() -> int:
    """Agent checks allowed per UTC day; past it items wait for the next day."""
    return max(0, _read_int_env("QBASAIR_MODERATION_DAILY_BUDGET", 2000))


def get_moderation_min_confidence() -> float:
    """An agent answer less confident than this is ``unsure`` (a person decides)."""
    try:
        value = float(os.environ.get("QBASAIR_MODERATION_MIN_CONFIDENCE", "0.7"))
    except ValueError:
        return 0.7
    return min(1.0, max(0.0, value))


def is_low_memory_mode() -> bool:
    """Return True when runtime caches should favor lower memory usage."""
    return read_bool_env("QBASAIR_LOW_MEMORY_MODE")


def get_runtime_sqlite_cache_pages() -> int:
    """Return the SQLite page-cache target for the current runtime mode."""
    if is_low_memory_mode():
        return LOW_MEMORY_SQLITE_CACHE_PAGES
    return DEFAULT_SQLITE_CACHE_PAGES


def get_runtime_mushaf_cache_limit() -> int | None:
    """Return the per-mushaf cache entry limit, or None when unlimited."""
    if is_low_memory_mode():
        return LOW_MEMORY_MUSHAF_CACHE_LIMIT
    return None


def get_runtime_query_cache_limit() -> int:
    """Return the did-you-mean cache entry limit.

    These caches are keyed by arbitrary user query strings, so they must always
    be bounded (previously unlimited in normal mode → unbounded memory growth).
    """
    if is_low_memory_mode():
        return LOW_MEMORY_QUERY_CACHE_LIMIT
    return DEFAULT_QUERY_CACHE_LIMIT


def get_cors_origins() -> list[str]:
    """Return allowed browser origins for the API."""
    raw_origins = os.environ.get("QBASAIR_CORS_ORIGINS", "")
    if not raw_origins.strip():
        return list(DEFAULT_CORS_ORIGINS)

    return [origin.strip().rstrip("/") for origin in raw_origins.split(",") if origin.strip()]
