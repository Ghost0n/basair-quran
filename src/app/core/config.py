def read_bool_env(name: str, default: bool = False) -> bool:
    """Parse a conventional boolean environment variable."""
    raw_value = os.environ.get(name)
    if raw_value is None:
        return default

    return raw_value.strip().lower() in {"1", "true", "yes", "on"}


