/**
 * A research as a carousel (سلسلة شرائح): a cover, one slide per quoted ayah
 * (with the note of the section that quotes it) and a closing slide — at most
 * ten slides, the common carousel limit. Pure, so it is tested without a
 * canvas; `share-card.ts` draws each slide.
 *
 * Contracts kept on every slide: the ayah is quoted whole with its reference;
 * AI-generated notes are labelled; a Tafssir-mode research carries its
 * experimental label on the cover and the closing slide.
 */
import type { ResearchSection } from "@q-basair/shared";

import { parseBlocks } from "./markdown-lite";
import type { ShareCardInput } from "./share-card";

import { t, tn } from "@/lib/i18n";

export const MAX_CAROUSEL_SLIDES = 10;
const NOTE_CHARS = 240;

export const TAFSSIR_BADGE = "قراءة تفسيرية تجريبية";
export const AI_NOTE_LABEL = "ملاحظة مولَّدة آلياً";

export type ShareableResearch = {
  title: string;
  summary?: string | null;
  mode?: "strict" | "tafssir" | null;
  sections: Pick<ResearchSection, "id" | "kind" | "title" | "body" | "ayahs">[];
  /** Section ids generated by AI (the document's `provenance.ai_sections`). */
  aiSectionIds?: string[];
  author?: string | null;
  /** A public link to the research (a published post). */
  url?: string | null;
};

type Helpers = { surahName: (surahId: number) => string; formatNumber: (value: number) => string };

/** The body as plain text: bullets and bold markers removed, whitespace collapsed. */
export function plainText(body: string): string {
  return parseBlocks(body)
    .flatMap((block) => (block.kind === "p" ? [block.inline] : block.items))
    .map((inline) => inline.map((part) => part.text).join(""))
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
}

export function clip(text: string, max: number): string {
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const space = cut.lastIndexOf(" ");
  return `${(space > max * 0.6 ? cut.slice(0, space) : cut).trim()} …`;
}

export function researchMeta(research: ShareableResearch, { formatNumber }: Helpers): string {
  const ayahs = research.sections.reduce((sum, section) => sum + section.ayahs.length, 0);
  const surahs = new Set(research.sections.flatMap((section) => section.ayahs.map((ref) => ref.surah_id))).size;
  const parts = [tn("{0} آية", ayahs, { 0: formatNumber(ayahs) })];
  if (surahs > 1) parts.push(tn("{0} سورة", surahs, { 0: formatNumber(surahs) }));
  if (research.author) parts.push(research.author);
  return parts.join(t("، "));
}

export function buildCarousel(research: ShareableResearch, helpers: Helpers): ShareCardInput[] {
  const { surahName, formatNumber } = helpers;
  const tafssir = research.mode === "tafssir";
  const ai = new Set(research.aiSectionIds ?? []);
  const verses: Extract<ShareCardInput, { kind: "verse" }>[] = [];
  for (const section of research.sections) {
    const note = section.body ? clip(plainText(section.body), NOTE_CHARS) : "";
    section.ayahs.forEach((ref, index) => {
      if (!ref.text) return;
      const withNote = index === 0 && note;
      verses.push({
        kind: "verse",
        text: ref.text,
        reference: t("سورة {0}، الآية {1}", { 0: surahName(ref.surah_id), 1: formatNumber(ref.ayah) }),
        heading: research.title,
        note: withNote ? note : null,
        noteLabel: withNote && (ai.has(section.id) || section.kind === "ai_answer") ? t(AI_NOTE_LABEL) : null,
      });
    });
  }
  const kept = verses.slice(0, MAX_CAROUSEL_SLIDES - 2);
  const firstAyah = kept[0]?.text ?? null;
  const slides: ShareCardInput[] = [
    {
      kind: "research",
      title: research.title,
      summary: research.summary,
      meta: researchMeta(research, helpers),
      // With ayah slides to follow, the cover stays light; alone, it quotes the first ayah.
      excerpt: kept.length ? null : firstAyah,
      badge: tafssir ? t(TAFSSIR_BADGE) : null,
    },
    ...kept,
    {
      kind: "closing",
      title: research.url ? t("اقرأ البحث كاملاً") : research.title,
      lines: [
        verses.length > kept.length
          ? t("في البحث {0} آية، هذه {1} منها.", { 0: formatNumber(verses.length), 1: formatNumber(kept.length) })
          : "",
        tafssir
          ? t("القراءة التفسيرية تجريبية: فهمٌ بشري يُناقَش، وليست حُجّة.")
          : t("القرآن هو الدليل، وما سواه فهمٌ يُناقَش."),
      ].filter(Boolean),
      url: research.url ?? null,
      badge: tafssir ? t(TAFSSIR_BADGE) : null,
    },
  ];
  const total = slides.length;
  return slides.map((slide, index) => ({ ...slide, counter: `${formatNumber(index + 1)} / ${formatNumber(total)}` }));
}
