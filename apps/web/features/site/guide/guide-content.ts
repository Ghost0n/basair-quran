/**
 * The feature guide at /guide (docs/public-site.md → "The guide"): every
 * feature of the app, by chapter, with the steps to use it and a real
 * screenshot or clip of the app (public/guide-media/<lang>/<platform>/<name>.webp|.mp4,
 * captured by scripts/capture-guide-media.mjs). It comes in two versions —
 * on a phone (the app, or the site in a phone's browser) and on a computer
 * (the website) — where the screens and the gestures differ. Every text goes
 * through t(), so the guide reads in all the interface languages.
 */
export type GuidePlatform = "mobile" | "web";
export const GUIDE_PLATFORMS: readonly GuidePlatform[] = ["mobile", "web"];

export type GuideMedia = { name: string; kind: "image" | "video" };

export type GuideTopic = {
  id: string;
  title: string;
  summary: string;
  steps: string[];
  tip?: string;
  media?: GuideMedia;
  /** Only in the iPhone / Android app (so not in the computer's guide). */
  appOnly?: boolean;
};

/** A topic as written: the phone's text, and what changes on a computer. */
type TopicSource = GuideTopic & {
  /** On a computer: these replace the phone's (its screenshot never shows there). */
  web?: Partial<Pick<GuideTopic, "summary" | "steps" | "tip" | "media">>;
  /** Only in one version of the guide. */
  only?: GuidePlatform;
};

type ChapterSource = Omit<GuideChapter, "topics"> & { topics: TopicSource[] };

export type GuideChapter = { id: string; icon: IconName; title: string; lead: string; topics: GuideTopic[] };

/** The screenshots exist in Arabic (right-to-left interfaces) and English (every other language). */
export function mediaLanguage(locale: string): "ar" | "en" {
  return locale === "ar" || locale === "fa" || locale === "ur" ? "ar" : "en";
}

/** Where a screenshot or clip is served from (public/guide-media/). */
export function mediaPath(locale: string, platform: GuidePlatform, media: GuideMedia, poster = false): string {
  return `/guide-media/${mediaLanguage(locale)}/${platform}/${media.name}.${media.kind === "video" && !poster ? "mp4" : "webp"}`;
}

/** The guide for a phone or a computer: each topic in that version, without those that don't exist there. */
export function guideChapters(platform: GuidePlatform): GuideChapter[] {
  return chapterSources()
    .map((chapter) => ({
      ...chapter,
      topics: chapter.topics
        .filter((topic) => (topic.only ?? platform) === platform && !(platform === "web" && topic.appOnly))
        .map(({ web, only: _only, ...topic }) => {
          if (platform === "mobile") return topic;
          const { media: _media, ...shared } = topic;
          return { ...shared, ...web };
        }),
    }))
    .filter((chapter) => chapter.topics.length > 0);
}

