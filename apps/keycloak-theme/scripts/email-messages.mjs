#!/usr/bin/env node
/**
 * The email-code mail in every theme language (docs/keycloak.md «Email code»).
 *
 * src/email-messages.json holds the mail's words per language (the web's
 * language codes); this script writes them as Keycloak message files,
 * src/email/messages/messages_<tag>.properties (Keycloak's tag: the web's zh
 * is zh-CN, a file suffix zh_CN), \u-escaped. Keycloak's own mails keep their
 * own words: these files only add the theme's qb* keys.
 *
 *   node scripts/email-messages.mjs           write the files
 *   node scripts/email-messages.mjs --check   fail when a file is stale (tests, CI)
 *
 * Fails when a language lacks a message, or a message holds an ASCII
 * apostrophe (MessageFormat would read it as a quote).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const webLocales = path.resolve(root, "../web/lib/i18n/locales");
const outDir = path.join(root, "src/email/messages");

const messages = Object.entries(JSON.parse(fs.readFileSync(path.join(root, "src/email-messages.json"), "utf8"))).filter(([key]) => !key.startsWith("//"));
const codes = ["ar", ...fs.readdirSync(webLocales).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5))].sort();

const problems = messages.flatMap(([key, texts]) =>
  codes.flatMap((code) => {
    const text = texts[code];
    if (typeof text !== "string") return [`${key} (${code}) is missing`];
    if (text.includes("'")) return [`${key} (${code}) has an ASCII apostrophe`];
    return [];
  }),
);
if (problems.length) {
  console.error(`src/email-messages.json: ${problems.join(", ")}`);
  process.exit(1);
}

// Per UTF-16 unit: a character beyond the BMP becomes its two halves, as Java reads them.
const escape = (text) =>
  text
    .split("")
    .map((unit) => (unit.charCodeAt(0) < 0x80 ? unit : `\\u${unit.charCodeAt(0).toString(16).padStart(4, "0")}`))
    .join("");

const files = Object.fromEntries(
  codes.map((code) => {
    const suffix = code === "zh" ? "zh_CN" : code;
    const lines = [
      "# Generated by scripts/email-messages.mjs from src/email-messages.json: do not edit by hand.",
      ...messages.map(([key, texts]) => `${key}=${escape(texts[code])}`),
      "",
    ];
    return [`messages_${suffix}.properties`, lines.join("\n")];
  }),
);

const stale = Object.entries(files).filter(([name, text]) => {
  const file = path.join(outDir, name);
  // A Windows checkout may hold the files with CRLF line ends: the words are what count.
  return !fs.existsSync(file) || fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== text;
});
const extra = fs.existsSync(outDir) ? fs.readdirSync(outDir).filter((name) => !(name in files)) : [];

if (process.argv.includes("--check")) {
  if (stale.length || extra.length) {
    console.error(`src/email/messages is stale (${[...stale.map(([name]) => name), ...extra].join(", ")}): run \`pnpm --filter @q-basair/keycloak-theme messages\`.`);
    process.exit(1);
  }
  console.log(`email messages up to date (${messages.length} keys × ${codes.length} locales)`);
} else {
  fs.mkdirSync(outDir, { recursive: true });
  for (const [name, text] of stale) fs.writeFileSync(path.join(outDir, name), text);
  for (const name of extra) fs.rmSync(path.join(outDir, name));
  console.log(`email messages: ${messages.length} keys × ${codes.length} locales → src/email/messages/`);
}
